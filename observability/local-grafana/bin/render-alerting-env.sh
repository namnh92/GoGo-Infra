#!/usr/bin/env bash
# Renders the Telegram credential for Grafana's administrative alerts out of SSM.
#
# ADR-0009 §F5. Two parameters, both SecureString, both declared in
# config/secrets.manifest.yml with `consumer: observability` — which is what
# keeps them out of the API's runtime environment. `render-env.sh` asks the
# manifest for `--consumer runtime`; these two are not in that answer, and a
# Telegram bot token has no business in the process environment of the most
# internet-exposed service in the estate.
#
# Output: `.env.alerting`, mode 0600, gitignored, loaded by compose into the
# Grafana container alone. Never committed, never printed, never echoed — the
# only thing this script says out loud is how many variables it wrote.
#
#   ./bin/render-alerting-env.sh          # environment defaults to dev
#   ENVIRONMENT=dev ./bin/render-alerting-env.sh
#
# Runs on the observability host (192.168.68.168) with credentials that can read
# /gogo/<env>/backend/observability/* — the deploy or monitor role already
# grants exactly that path, so no IAM change and no new role.
set -euo pipefail

ENVIRONMENT="${ENVIRONMENT:-dev}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${here}/.env.alerting"
prefix="/gogo/${ENVIRONMENT}/backend/observability"

command -v aws >/dev/null || { echo "aws CLI required" >&2; exit 1; }

# path suffix -> environment variable. Kept in step with the manifest by
# scripts/ci/alerting-provisioning.test.sh, which fails if the two drift.
declare -a PARAMS=(
  "grafana-telegram-bot-token:GRAFANA_TELEGRAM_BOT_TOKEN"
  "grafana-telegram-chat-id:GRAFANA_TELEGRAM_CHAT_ID"
)

umask 077
tmp="$(mktemp "${TMPDIR:-/tmp}/alerting-env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
chmod 600 "$tmp"

{
  echo "# GENERATED by bin/render-alerting-env.sh — do not edit, do not commit."
  echo "# Rendered from ${prefix}/* at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
} >>"$tmp"

missing=()
for pair in "${PARAMS[@]}"; do
  path="${pair%%:*}"
  var="${pair#*:}"
  if value="$(aws ssm get-parameter --name "${prefix}/${path}" --with-decryption \
      --query 'Parameter.Value' --output text 2>/dev/null)" && [[ -n "$value" && "$value" != "None" ]]; then
    printf '%s=%s\n' "$var" "$value" >>"$tmp"
    unset value
  else
    missing+=("${prefix}/${path}")
  fi
done

# All or nothing. A half-rendered file would let Grafana start with a chat id
# and no token, and Grafana would refuse the contact point with an error nobody
# is watching for — the loud failure belongs here, where someone ran a command
# and is waiting for its exit code.
if [[ "${#missing[@]}" -gt 0 ]]; then
  echo "refusing to write ${out}: parameters missing or empty" >&2
  printf '  - %s\n' "${missing[@]}" >&2
  echo "The owner creates the Telegram bot token and chat id; put them in SSM with" >&2
  echo "  scripts/secrets/put.sh ${ENVIRONMENT} observability/grafana-telegram-bot-token" >&2
  exit 1
fi

mv "$tmp" "$out"
trap - EXIT
chmod 600 "$out"

echo "wrote $(grep -cE '^[A-Z_]+=' "$out") variables into ${out} (mode 0600, gitignored)"
