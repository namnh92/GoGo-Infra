#!/usr/bin/env bash
# Renders Prometheus' basic-auth files out of `.env`.
#
# ADR-0007 §E4 asked whether bind rules plus a host firewall are enough on
# their own, measured against §E8's test: *would PROD refuse this?* PROD would
# refuse an unauthenticated remote-write receiver, so DEV does not get one
# either — that is the whole point of E8, and "it is only DEV" is the argument
# it exists to reject.
#
# Two files come out, neither ever committed:
#   prometheus/web.yml               the bcrypt hash Prometheus checks against
#   prometheus/basic_auth_password   cleartext, for Prometheus' own self-scrape
#
# bcrypt is not in coreutils, so the hash is produced by the httpd image the
# host already has a Docker daemon for. No new tool to install, and no
# password on any command line that a `ps` would show.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="${here}/.env"

if [[ ! -f "$env_file" ]]; then
  echo "no ${env_file} — copy .env.example and fill it in first" >&2
  exit 1
fi

set -a
# shellcheck disable=SC1090  # path is the caller's .env, by design
source "$env_file"
set +a

: "${PROMETHEUS_BASIC_AUTH_USER:?set PROMETHEUS_BASIC_AUTH_USER in .env}"
: "${PROMETHEUS_BASIC_AUTH_PASSWORD:?set PROMETHEUS_BASIC_AUTH_PASSWORD in .env}"

# The self-scrape's username is literal in prometheus.yml because Prometheus
# expands no variables there. If the two disagree, Prometheus starts, scrapes
# itself, gets 401, and reports nothing about its own storage — a silence that
# looks exactly like a healthy quiet system.
scrape_user="$(sed -n 's/^ *username: *\([^ ]*\) *$/\1/p' "${here}/prometheus/prometheus.yml" | head -1)"
if [[ "$scrape_user" != "$PROMETHEUS_BASIC_AUTH_USER" ]]; then
  echo "prometheus.yml self-scrapes as '${scrape_user}' but .env sets '${PROMETHEUS_BASIC_AUTH_USER}'." >&2
  echo "Change one of them; a mismatch 401s the self-scrape silently." >&2
  exit 1
fi

if ! command -v docker >/dev/null 2>&1; then
  echo "docker is required to produce the bcrypt hash" >&2
  exit 1
fi

# -i reads the password on stdin, so it never appears in the process list.
hash="$(printf '%s' "$PROMETHEUS_BASIC_AUTH_PASSWORD" \
  | docker run --rm -i httpd:2.4-alpine htpasswd -niB "$PROMETHEUS_BASIC_AUTH_USER" \
  | cut -d: -f2-)"

if [[ -z "$hash" ]]; then
  echo "htpasswd produced no hash" >&2
  exit 1
fi

umask 077
cat > "${here}/prometheus/web.yml" <<YAML
# GENERATED by bin/render-web-config.sh — do not edit, do not commit.
basic_auth_users:
  ${PROMETHEUS_BASIC_AUTH_USER}: ${hash}
YAML

printf '%s' "$PROMETHEUS_BASIC_AUTH_PASSWORD" > "${here}/prometheus/basic_auth_password"
chmod 600 "${here}/prometheus/web.yml" "${here}/prometheus/basic_auth_password"

echo "wrote prometheus/web.yml and prometheus/basic_auth_password (0600, gitignored)"
